        $this->assertSame(
            ['app/Artifacts/FilesystemArtifactStore.php (1)'],
            $sites,
            'the builds/ key prefix must be built in exactly one place (SPEC 8.8.1): '.implode('; ', $sites),
        );
    }

    /**
     * 🛑 SPEC 8.8.2's reserved filenames must be refused by the ingestor, and
     * the identifiers must be the abuse corpus's.
     *
     * A cheap structural check, not a substitute for ArtifactIngestorTest: it
     * asserts that every `archive` case in the corpus still has an expectation
     * that RejectionCode can actually produce. A corpus case expecting an
     * identifier no enum case carries would otherwise fail only as a confusing
     * assertion mismatch, in a dataset, long after the rename that caused it.
     */
    public function test_every_archive_corpus_case_names_a_real_rejection_code(): void
    {
        /** @var array{cases: list<array<string, string>>} $corpus */
        $corpus = json_decode(
            (string) file_get_contents(base_path('tests/Fixtures/AbuseCorpus/corpus.json')),
            true,
            64,
            JSON_THROW_ON_ERROR,
        );

        $known = array_map(
            static fn (RejectionCode $code): string => $code->value,
            RejectionCode::cases(),
        );

        $unknown = [];

        foreach ($corpus['cases'] as $case) {
            if (($case['category'] ?? null) !== 'archive') {
                continue;
            }

            if (! in_array($case['expect'], $known, true)) {
                $unknown[] = $case['id'].' expects '.$case['expect'];
            }
        }

        $this->assertSame(
            [],
            $unknown,
            'corpus cases expecting an identifier no RejectionCode carries: '.implode('; ', $unknown),
        );
    }

    /**
     * 🛑 SPEC 9.3.2: "An architecture test MUST forbid any code path setting a
     * public CDN cache directive outside the single three-way public check
     * (project public ∧ version public ∧ rule publicly cacheable)."
     *
     * This is that test. The failure it guards is the worst one in the serving
     * path: a private document handed to a shared cache. That does not look
     * like a bug from inside — the response is a correct 200 with correct
     * content — and it is discovered by a reader being served somebody else's
     * private page.
     *
     * Two things are asserted: nothing outside CachePolicy may construct a
     * publicly cacheable set of directives, and nothing outside CacheDirectives
     * may write a public directive literal. The first catches a caller who
     * found the value object; the second catches a header set by hand.
     *
     * 🛑 It does NOT forbid naming `CDN-Cache-Control`. The first version did,
     * and it flagged `ArtifactHandoff::PRESERVED_HEADERS` — which lists the
     * header precisely so nginx re-emits it. Forbidding the name would have
     * meant allowlisting the one file that must mention it, and an allowlist
     * that grows by one legitimate case each phase stops being a gate. What
     * §9.3.2 forbids is *setting a public directive*, and that is what is
     * checked.
     */
    public function test_only_the_cache_policy_may_emit_a_public_cdn_directive(): void
    {
        $offenders = [];

        foreach ($this->sourceFiles() as $file) {
            $relative = str_replace(DIRECTORY_SEPARATOR, '/', str_replace(base_path().DIRECTORY_SEPARATOR, '', $file));

            // The policy and the value object it constructs are the single
            // permitted site. Allowlisted by path, so the exemption cannot be
            // claimed by writing the right words somewhere else.
            if (in_array($relative, ['app/Serving/CachePolicy.php', 'app/Serving/CacheDirectives.php'], true)) {
                continue;
            }

            $source = $this->code($file);

            if (str_contains($source, 'publiclyCacheable')) {
                $offenders[] = $relative.' constructs publicly cacheable directives';
            }

            // The literal a hand-written public directive would have to contain.
            if (preg_match('/[\'"]public,\s*max-age/', $source) === 1) {
                $offenders[] = $relative.' writes a public cache directive literal';
            }
        }

        $this->assertSame(
            [],
            $offenders,
            'only CachePolicy may decide public cacheability (SPEC 9.3.2): '.implode('; ', $offenders),
        );
    }

    /**
     * 🛑 SPEC 4.3/2 and SPEC 8.9.8: documentation bytes never traverse PHP.
     *
     * Asserted as the absence of a file read on the serving path. The handoff
     * exists so that PHP authorises and the edge moves bytes; a
     * `file_get_contents` or a `readfile` in App\Serving would be the
     * architecture quietly becoming something else, and SPEC 9.2's flat-memory
     * budget would go with it.
     *
     * `file_get_contents` IS permitted in the serving TESTS, which read
     * deploy/nginx.conf to assert its contents — that is configuration, not an
     * artifact, and the tests are not the serving path.
     */
    public function test_nothing_on_the_serving_path_reads_a_file(): void
    {
        $offenders = [];

        foreach ($this->sourceFiles() as $file) {
            $relative = str_replace(DIRECTORY_SEPARATOR, '/', str_replace(base_path().DIRECTORY_SEPARATOR, '', $file));

            if (! str_starts_with($relative, 'app/Serving/')) {
                continue;
            }

            $source = $this->code($file);

            /*
             * 🛑 `file(` is deliberately NOT in this list, and the reason is
             * worth keeping: as a bare substring it matches
             * `FileOutcome::file(` and flagged both the resolver and the value
             * object it returns. PHP's own `file()` is vanishingly rare and the
             * needle for it is unusable, so the list names the readers that
             * actually move bytes.
             */
            foreach ([
                'file_get_contents',
                'file_put_contents',
                'readfile',
                'fpassthru',
                'fread',
                'fopen',
                'SplFileObject',
            ] as $reader) {
                if (str_contains($source, $reader)) {
                    $offenders[] = $relative.' uses '.$reader;
                }
            }
        }

        $this->assertSame(
            [],
            $offenders,
            'documentation bytes must not traverse PHP (SPEC 8.9.8): '.implode('; ', $offenders),
        );
    }

    /**
     * 🛑 SPEC 10.8: "**One** registry, because ten uncoordinated counters
     * produce an irreproducible stale-authorisation bug."
     *
     * So exactly one class may increment an epoch column. The bug the
     * requirement names is specific and nasty: with several places bumping,
     * one of them forgets a case, and the resulting staleness depends on which
     * code path ran — so it cannot be reproduced from the symptom.
     *
     * Asserted on the column names rather than on a method, because the bypass
     * is writing the SQL by hand rather than calling the wrong helper.
     */
    public function test_only_the_invalidation_registry_bumps_an_epoch(): void
    {
        $epochColumns = [
            'routing_epoch',
            'authz_epoch',
            'identity_epoch',
            'permission_epoch',
            'serving_epoch',
            'search_generation',
            'policy_generation',
        ];

        $offenders = [];

        foreach ($this->sourceFiles() as $file) {
            $relative = str_replace(DIRECTORY_SEPARATOR, '/', str_replace(base_path().DIRECTORY_SEPARATOR, '', $file));

            /*
             * The registry itself, and the migrations that create the columns.
             * Allowlisted by path so the exemption cannot be claimed elsewhere
             * by writing the right words.
             */
            if ($relative === 'app/Support/Invalidation.php' || str_starts_with($relative, 'database/migrations/')) {
                continue;
            }

            $source = $this->code($file);

            foreach ($epochColumns as $column) {
                // An increment, in any spelling. A read is fine - SPEC 8.9.10
                // requires the resolver to READ routing_epoch from the snapshot.
                if (preg_match('/'.preg_quote($column, '/').'\s*(\+\+|\+\s*1|=\s*\S+\s*\+)/', $source) === 1) {
                    $offenders[] = $relative.' increments '.$column;
                }
            }
        }

        $this->assertSame(
            [],
            $offenders,
            'only App\Support\Invalidation may bump an epoch (SPEC 10.8): '.implode('; ', $offenders),
        );
    }

    /**
     * 🛑 SPEC 8.3.9: "The system MUST route every outbound request derived
     * from user-supplied configuration ... through **one**
     * `HardenedEgressClient` ... One class, sole call site,
     * architecture-tested."
     *
     * This is that test, and it is the same argument SPEC 8.8.2 makes for
     * `ArtifactIngestor`: a second outbound path is not a duplication bug but
     * an **unvalidated** one. It gets written in a hurry, for a webhook or an
     * avatar fetch or an OIDC discovery document, by somebody who did not know
     * this class existed - and it is the one the attacker uses, because it is
     * the one with no address policy, no pin and no redirect refusal.
     *
     * Two things are forbidden outside `app/Egress`: making a request by any
     * mechanism, and constructing the transport or the options. The second
     * catches a caller who found the pieces and assembled a client of their
     * own with the controls turned off.
     *
     * `app/Providers` is allowlisted **by path**, exactly as the artifact test
     * allowlists it, because binding a class in a container is not calling it.
     * A path rather than a comment marker, so the exemption cannot be claimed
     * by writing the right words in a file somewhere else.
     */
    public function test_only_the_egress_namespace_makes_outbound_requests(): void
    {
        $offenders = [];

        /*
         * Each entry is a way to speak HTTP from PHP. `file_get_contents` and
         * `fopen` are included because a URL is a stream wrapper argument and
         * they are the two that do not look like network calls at a glance -
         * which is why they are the two that get written.
         */
        $mechanisms = [
            'curl_init(' => 'calls curl directly',
            'curl_exec(' => 'calls curl directly',
            'GuzzleHttp\\' => 'names Guzzle',
            'Facades\\Http' => 'uses the Http facade',
            'Http::get(' => 'uses the Http facade',
            'Http::post(' => 'uses the Http facade',
            'Http::withHeaders(' => 'uses the Http facade',
            'fsockopen(' => 'opens a socket',
            'stream_socket_client(' => 'opens a socket',
            'stream_context_create(' => 'builds a stream context, which is how a URL fetch is configured',
            'new PinnedCurlTransport' => 'constructs the egress transport',
            'new HardenedEgressClient' => 'constructs a second egress client',
            'new EgressOptions' => 'constructs its own egress budget',
        ];

        /*
         * 🛑 One allowlisted file, and the boundary it sits on the right side
         * of. SPEC 8.3.9's rule is about requests "derived from user-supplied
         * configuration"; `doctor` opens a socket to two **hard-coded** hosts
         * — `mailpit` and `phpmyadmin` — to assert SPEC 8.1.3, that neither is
         * reachable in production. No user input reaches it, there is no URL,
         * and it reads no bytes.
         *
         * Stated rather than quietly skipped, because an allowlist that grows
         * by one legitimate case per phase stops being a gate. If a second
         * entry is ever proposed, the question to ask is whether its
         * destination can be influenced by anything a tenant controls - and if
         * it can, the answer is the egress client, not this list.
         */
        $fixedHostLivenessProbe = ['app/Console/Commands/DoctorCommand.php'];

        foreach ($this->sourceFiles() as $file) {
            $relative = str_replace(DIRECTORY_SEPARATOR, '/', str_replace(base_path().DIRECTORY_SEPARATOR, '', $file));

            if (str_starts_with($relative, 'app/Egress/') || str_starts_with($relative, 'app/Providers/')) {
                continue;
            }

            if (in_array($relative, $fixedHostLivenessProbe, true)) {
                continue;
            }

            $source = $this->code($file);

            foreach ($mechanisms as $needle => $what) {
                if (str_contains($source, $needle)) {
                    $offenders[] = $relative.' '.$what;
                }
            }

            // A URL handed to a stream function, in either quoting style.
            if (preg_match('/(file_get_contents|fopen|readfile|simplexml_load_file)\s*\(\s*[\'"]https?:/', $source) === 1) {
                $offenders[] = $relative.' fetches a URL through a stream function';
            }
        }

        $this->assertSame(
            [],
            $offenders,
            'only App\Egress may make an outbound request (SPEC 8.3.9): '.implode('; ', $offenders),
        );
    }

    /**
     * 🛑 Nothing in the application stands the egress address policy down.
     *
     * `EgressOptions::$enforceAddressPolicy` exists so that the redirect and
     * byte-cap controls can be proven against a **running** loopback origin -
     * SPEC 18.18's lesson from Phase 04, that a config asserted only against a
     * constant is a config nobody has run. The flag is a test affordance, and
     * this is what keeps it one.
     *
     * It is deliberately NOT reachable from the environment: SPEC 20.4's
     * invariant is that no security control sits behind a flag that defaults
     * open, and the cheapest way to honour that is to have no flag an operator
     * can reach. `EgressConfigurationTest` asserts the shipped config has none.
     */
    public function test_nothing_in_the_application_disables_the_egress_address_policy(): void
    {
        $offenders = [];

        foreach ($this->sourceFiles() as $file) {
            $relative = str_replace(DIRECTORY_SEPARATOR, '/', str_replace(base_path().DIRECTORY_SEPARATOR, '', $file));
            $source = $this->code($file);

            if (preg_match('/enforceAddressPolicy\s*:\s*false/', $source) === 1) {
                $offenders[] = $relative.' passes enforceAddressPolicy: false';
            }

            if (preg_match('/[\'"]enforce_address_policy[\'"]\s*=>\s*false/', $source) === 1) {
                $offenders[] = $relative.' configures enforce_address_policy => false';
            }
        }

        $this->assertSame(
            [],
            $offenders,
            'the egress address policy may not be disabled in application code (SPEC 8.3.9): '.implode('; ', $offenders),
        );
    }

    /**
     * 🛑 Every log channel redacts secrets (SPEC 8.5.21).
     *
     * Phase 05's exit criterion is "no token appears in any log, at any log
     * level". The level is the easy half - a Monolog processor runs on every
     * record a channel accepts. The criterion is lost by a **channel** being
     * added six phases from now for a new deployment profile, by somebody who
     * has never read `App\Credentials\SecretRedactor`.
     *
