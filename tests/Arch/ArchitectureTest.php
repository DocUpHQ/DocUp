declare(strict_types=1);

namespace Tests\Arch;

use App\Artifacts\RejectionCode;
use Tests\TestCase;

/**
 * The SPEC 4.3 invariants, enforced by CI rather than by intention.
 *
 * These are deliberately crude: they read the source tree. That is the point -
 * an architecture test that depends on the application booting, or on reflection
 * over loaded classes, stops protecting the thing it was written for the moment
 * the code it guards fails to load. Grepping the tree always runs.
 *
 * Every assertion here maps to a named requirement. A test that cannot name the
 * requirement it defends should not be in this file.
 */
final class ArchitectureTest extends TestCase
{
    /** @return list<string> */
    private function sourceFiles(string $extension = 'php'): array
    {
        $roots = ['app', 'config', 'database', 'routes', 'bootstrap'];
        $files = [];

        foreach ($roots as $root) {
            $dir = base_path($root);

            if (! is_dir($dir)) {
                continue;
            }

            /** @var \SplFileInfo $file */
            foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($dir)) as $file) {
                if (str_contains($file->getPathname(), DIRECTORY_SEPARATOR.'cache'.DIRECTORY_SEPARATOR)) {
                    continue;   // generated by the framework, not first-party source
                }

                if ($file->isFile() && $file->getExtension() === $extension) {
                    $files[] = $file->getPathname();
                }
            }
        }

        return $files;
    }

    /** @return list<string> */
    private function migrations(): array
    {
        return glob(base_path('database/migrations/*.php')) ?: [];
    }

    /**
     * Source with comments and string literals removed.
     *
     * These tests analyse CODE. Twice now a version of this suite has failed on
     * its own documentation - a comment explaining the rule tripping the rule -
     * so stripping comments is not a convenience, it is what makes the
     * assertion mean what it says. Uses the tokeniser rather than a regex
     * because a regex cannot tell a comment from a string containing "//".
     */
    private function code(string $file): string
    {
        $tokens = token_get_all((string) file_get_contents($file));
        $out = '';

        foreach ($tokens as $token) {
            if (is_array($token)) {
                if (in_array($token[0], [T_COMMENT, T_DOC_COMMENT], true)) {
                    continue;
                }

                $out .= $token[1];

                continue;
            }

            $out .= $token;
        }

        return $out;
    }

    /**
     * 🛑 SPEC 9.1.3: exactly ONE AUTO_INCREMENT column may exist in the schema -
     * the surrogate id on the FULLTEXT search table - allowlisted by name.
     *
     * ADR 0004 is why the allowlist names a surrogate rather than FTS_DOC_ID:
     * declaring FTS_DOC_ID while a FULLTEXT index exists makes bulk inserts fail
     * with ERROR 182, so InnoDB manages it hidden and we never declare it.
     */
    public function test_only_the_allowlisted_auto_increment_exists(): void
    {
        // SPEC 9.1.3 allows exactly one AUTO_INCREMENT: the surrogate id on the
        // FULLTEXT search table. Laravel's own queue tables are a separate
        // matter - `jobs.id` is part of the queue driver's contract and the
        // driver reads it, so converting it to BINARY(16) would break the
        // queue rather than improve anything. They are framework-owned, not
        // part of DocUp's data model, and are allowlisted BY NAME for the same
        // reason SPEC 9.1.3 allowlists the search table by name.
        $allowed = [
            'search_documents',   // SPEC 9.1.3 / ADR 0004: InnoDB FULLTEXT surrogate
            'jobs',               // framework-owned: Laravel queue driver contract
            'job_batches',        // framework-owned
            'failed_jobs',        // framework-owned
        ];
        $offenders = [];

        foreach ($this->migrations() as $file) {
            $source = $this->code($file);

            // Laravel spells an auto-incrementing column id(), increments(),
            // bigIncrements() and friends. uuidKey() is ours and is not one.
            if (! preg_match('/\$table->(id|increments|bigIncrements|smallIncrements|mediumIncrements|tinyIncrements)\s*\(/', $source)) {
                continue;
            }

            $isAllowed = false;

            foreach ($allowed as $table) {
                if (str_contains($source, "'{$table}'")) {
                    $isAllowed = true;
                    break;
                }
            }

            if (! $isAllowed) {
                $offenders[] = basename($file);
            }
        }

        $this->assertSame(
            [],
            $offenders,
            'auto-incrementing keys outside the allowlist (SPEC 9.1.3). Use $table->uuidKey(). Offenders: '
            .implode(', ', $offenders),
        );
    }

    /**
     * 🛑 SPEC 4.4 / 11.4: there is no open core. EntitlementResolver is
     * precisely the hook an open-core pivot would use, so it must not exist,
     * and no feature may be gated by a licence check.
     */
    public function test_there_is_no_entitlement_or_licence_gate(): void
    {
        $forbidden = [
            'EntitlementResolver',
            'licence_key',
            'license_key',
            'LicenseKey',
            'isPremium',
            'requiresEnterprise',
        ];

        $offenders = [];

        foreach ($this->sourceFiles() as $file) {
            $source = $this->code($file);

            foreach ($forbidden as $needle) {
                // Skip the comment that explains the rule.
                if (str_contains($source, $needle) && ! str_contains($source, 'SPEC 4.4')) {
                    $offenders[] = basename($file).' => '.$needle;
                }
            }
        }

        $this->assertSame([], $offenders, 'no-open-core pledge violated (SPEC 4.4): '.implode(', ', $offenders));
    }

    /**
     * 🛑 SPEC 8.22.11 / 20.4: every installation-level escape hatch lives in the
     * one unsafe-modes registry. A flag introduced anywhere else escapes its
     * audit event, its dashboard banner and its doctor finding.
     */
    public function test_every_unsafe_flag_is_in_the_registry(): void
    {
        $registry = (string) file_get_contents(base_path('config/docup.php'));
        $declared = [];

        foreach ($this->sourceFiles() as $file) {
            preg_match_all(
                '/DOCUP_(?:UNSAFE|DANGEROUSLY|ACKNOWLEDGE|ALLOW)_[A-Z0-9_]+/',
                $this->code($file),
                $matches,
            );

            foreach ($matches[0] as $flag) {
                $declared[$flag] = basename($file);
            }
        }

        $missing = [];

        foreach ($declared as $flag => $where) {
            if (! str_contains($registry, $flag)) {
                $missing[] = "{$flag} (in {$where})";
            }
        }

        $this->assertSame(
            [],
            $missing,
            'unsafe flags outside the SPEC 20.4 registry: '.implode(', ', $missing),
        );
    }

    /**
     * 🛑 SPEC 9.1.1 / ADR 0006: the UUID key must be held as RAW BYTES. An
     * attribute cast on the key is the implementation that makes belongsToMany
     * return silently empty, and it is the obvious-looking thing a future
     * contributor will reach for.
     */
    public function test_the_uuid_key_is_not_cast(): void
    {
        $trait = $this->code(base_path('app/Concerns/HasUuidKey.php'));

        $this->assertStringNotContainsString(
            'casts[$this->getKeyName()]',
            $trait,
            'the primary key must not be cast (ADR 0006): a cast breaks belongsToMany silently',
        );

        foreach ($this->sourceFiles() as $file) {
            $source = $this->code($file);

            if (preg_match("/'id'\s*=>\s*(?:BinaryUuid|Uuid)::class/", $source)) {
                $this->fail('a model casts its key to a UUID object (ADR 0006): '.basename($file));
            }
        }
    }

    /**
     * SPEC 9.1.4: security tokens are CSPRNG, never UUIDv7, because v7 embeds a
     * readable creation timestamp and these values are enumerable.
     */
    public function test_tokens_are_not_generated_from_uuid_v7(): void
    {
        foreach ($this->sourceFiles() as $file) {
            $source = $this->code($file);

            foreach (['token', 'secret', 'nonce'] as $hint) {
                if (preg_match('/\$'.$hint.'[A-Za-z]*\s*=\s*(?:Str::)?uuid7?\s*\(/i', $source)) {
                    $this->fail(
                        'a security token is derived from a UUID (SPEC 9.1.4) in '.basename($file)
                        .'. Use random_bytes().',
                    );
                }
            }
        }

        // Assert the sweep actually ran over something, so the test cannot
        // pass by silently finding no files to check.
        $this->assertNotEmpty($this->sourceFiles(), 'the source sweep found no files');
    }

    /**
     * SPEC 8.1.3: the production compose file must not carry the development
     * images. Duplicated from ComposeFilesTest deliberately - that test proves
     * the behaviour, this one makes it an architectural invariant that fails the
     * arch suite, which is one of the three suites CLAUDE.md says always runs.
     */
    public function test_production_compose_carries_no_development_images(): void
    {
        $production = (string) file_get_contents(base_path('compose.yaml'));

        // Match service declarations and image references only. A previous
        // version of this test grepped the whole file and failed on the comment
        // explaining the requirement, which is a test asserting against its own
        // documentation rather than against the configuration.
        foreach (['mailpit', 'phpmyadmin', 'adminer'] as $name) {
            $this->assertDoesNotMatchRegularExpression(
                '/^\s{2}'.preg_quote($name, '/').'\s*:/mi',
                $production,
                "compose.yaml declares a [{$name}] service (SPEC 8.1.3)",
            );
            $this->assertDoesNotMatchRegularExpression(
                '/^\s*image:\s*\S*'.preg_quote($name, '/').'/mi',
                $production,
                "compose.yaml references a [{$name}] image (SPEC 8.1.3)",
            );
        }
    }

    /** SPEC 15.6: SPDX headers on first-party source. */
    public function test_first_party_source_carries_an_spdx_header(): void
    {
        $missing = [];

        foreach ($this->sourceFiles() as $file) {
            $head = (string) file_get_contents($file, length: 400);

            if (! str_contains($head, 'SPDX-License-Identifier')) {
                $missing[] = str_replace(base_path().DIRECTORY_SEPARATOR, '', $file);
            }
        }

        $this->assertSame([], $missing, 'files without an SPDX header (SPEC 15.6): '.implode(', ', $missing));
    }

    /**
     * 🛑 SPEC 8.8.2: "Exactly one `ArtifactIngestor` MUST validate every
     * incoming tree, and an architecture test MUST prove no caller bypasses
     * it."
     *
     * This is that test. It proves containment by the only route that cannot be
     * talked around: writing an artifact means calling ArtifactStore::put(), so
     * if nothing outside App\Artifacts calls put(), nothing outside can store a
     * byte without going through the ingestor.
     *
     * The reason the specification asks for a test rather than a convention is
     * that a second ingest path is not a duplication bug, it is an unvalidated
     * one. It gets written in a hurry, for an import or a migration, by somebody
     * who did not know the first one existed — and it is the one the attacker
     * uses.
     */
    public function test_only_the_artifact_namespace_writes_to_the_artifact_store(): void
    {
        $offenders = [];

        foreach ($this->sourceFiles() as $file) {
            $relative = str_replace(base_path().DIRECTORY_SEPARATOR, '', $file);
            $relative = str_replace(DIRECTORY_SEPARATOR, '/', $relative);

            if (str_starts_with($relative, 'app/Artifacts/')) {
                continue;
            }

            $source = $this->code($file);

            // The store is reached either through the interface or through a
            // concrete driver. Naming any of them outside the namespace is the
            // thing being refused, because a reference is what a call needs.
            foreach (['ArtifactStore', 'LocalArtifactStore', 'S3ArtifactStore', 'ArtifactIngestor'] as $symbol) {
                if (! str_contains($source, $symbol)) {
                    continue;
                }

                /*
                 * A service provider must name these to bind them, and that is
                 * the one legitimate reference: binding a class is not calling
                 * put(). Allowlisted by path rather than by a comment marker, so
                 * the exemption cannot be claimed by writing the right words.
                 */
                if (str_starts_with($relative, 'app/Providers/')) {
                    continue;
                }

                $offenders[] = $relative.' references '.$symbol;
            }
        }

        $this->assertSame(
            [],
            $offenders,
            'only App\Artifacts may reach the artifact store (SPEC 8.8.2): '.implode('; ', $offenders),
        );
    }

    /**
     * 🛑 SPEC 8.8.1: "No project slug, version slug, language or user-supplied
     * name MUST appear in any storage key, so renaming can never strand or
     * invalidate stored artifacts."
     *
     * Enforced as a shape rather than by searching for the word "slug": the key
     * grammar is `builds/{build_id}/{media_type}/…`, so exactly one expression
     * in the tree may produce the `builds/` prefix, and it must build it from a
     * build id. A second place that concatenates `'builds/'` is how a slug gets
     * in, whatever it is called at the time.
     */
    public function test_the_artifact_key_prefix_has_one_construction_site(): void
    {
        $sites = [];

        foreach ($this->sourceFiles() as $file) {
            $relative = str_replace(base_path().DIRECTORY_SEPARATOR, '', $file);
            $relative = str_replace(DIRECTORY_SEPARATOR, '/', $relative);

            if (preg_match_all("/'builds\/'/", $this->code($file), $matches) > 0) {
                $sites[] = $relative.' ('.count($matches[0]).')';
            }
        }

        $this->assertSame(
            ['app/Artifacts/FilesystemArtifactStore.php (1)'],
            $sites,
            'the builds/ key prefix must be built in exactly one place (SPEC 8.8.1): '.implode('; ', $sites),
        );
    }

    /**
     * 🛑 SPEC 8.8.2's reserved filenames must be refused by the ingestor, and
     * the identifiers must be the abuse corpus's.
     *
     * A cheap structural check, not a substitute for ArtifactIngestorTest: it
     * asserts that every `archive` case in the corpus still has an expectation
     * that RejectionCode can actually produce. A corpus case expecting an
     * identifier no enum case carries would otherwise fail only as a confusing
     * assertion mismatch, in a dataset, long after the rename that caused it.
     */
    public function test_every_archive_corpus_case_names_a_real_rejection_code(): void
    {
        /** @var array{cases: list<array<string, string>>} $corpus */
        $corpus = json_decode(
            (string) file_get_contents(base_path('tests/Fixtures/AbuseCorpus/corpus.json')),
            true,
            64,
            JSON_THROW_ON_ERROR,
        );

        $known = array_map(
            static fn (RejectionCode $code): string => $code->value,
            RejectionCode::cases(),
        );

        $unknown = [];

        foreach ($corpus['cases'] as $case) {
            if (($case['category'] ?? null) !== 'archive') {
                continue;
            }

            if (! in_array($case['expect'], $known, true)) {
                $unknown[] = $case['id'].' expects '.$case['expect'];
            }
        }

        $this->assertSame(
            [],
            $unknown,
            'corpus cases expecting an identifier no RejectionCode carries: '.implode('; ', $unknown),
        );
    }
}
