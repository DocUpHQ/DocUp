# Renders squid.conf from §8.5.9's allowlist file and execs squid.
#
# The configuration is GENERATED rather than shipped, because the one thing
# an operator edits — the host list — must not require them to understand
# squid's ACL ordering. Everything that is a security decision is written
# here, in one place, and the only thing the file contributes is names.

set -eu

ALLOWLIST="${DOCUP_EGRESS_ALLOWLIST:-/etc/docup/egress-allowlist.conf}"
# 🛑 Rendered into the writable tmpfs, NOT into /etc/squid. A tmpfs mounted
# over /etc/squid hides `mime.conf` and the error pages the image ships
# there, and squid exits with "MIME Config Table ... No such file or
# directory" — which reads like a broken image rather than a mount. Keeping
# the package's own directory intact and putting only the generated policy
# on a tmpfs gives both: a read-only root filesystem and a configuration
# that exists only in memory, so an operator cannot edit the policy in place
# and have the edit survive a restart. The allowlist file is the only way in.
CONF=/var/run/squid/squid.conf
PORT="${DOCUP_PROXY_PORT:-3128}"

if [ ! -r "$ALLOWLIST" ]; then
    echo "docup-proxy: allowlist $ALLOWLIST is not readable; refusing to start" >&2
    echo "docup-proxy: an unreadable allowlist would otherwise render an empty one," >&2
    echo "docup-proxy: and an empty allowlist denying everything looks exactly like a" >&2
    echo "docup-proxy: working proxy until somebody's build needs PyPI (§8.5.9)." >&2
    exit 1
fi

# 🛑 Exact hostnames only. A leading dot is squid's subdomain wildcard, and
# `.pythonhosted.org` would hand every build any host anybody can register
# under that name. Refused loudly at start-up rather than silently dropped:
# an operator who wrote a wildcard meant something by it and needs to know
# it did not happen.
HOSTS=""
LINE_NO=0
while IFS= read -r line || [ -n "$line" ]; do
    LINE_NO=$((LINE_NO + 1))
    host=$(printf '%s' "$line" | sed 's/#.*//' | tr -d ' \t\r')
    [ -z "$host" ] && continue

    case "$host" in
        .*|*\**)
            echo "docup-proxy: $ALLOWLIST line $LINE_NO: '$host' is a wildcard; only exact hostnames are permitted (§8.5.9)" >&2
            exit 1
            ;;
        *[!a-zA-Z0-9.-]*)
            echo "docup-proxy: $ALLOWLIST line $LINE_NO: '$host' is not a hostname" >&2
            exit 1
            ;;
    esac

    HOSTS="$HOSTS $host"
done < "$ALLOWLIST"

if [ -z "$HOSTS" ]; then
    echo "docup-proxy: $ALLOWLIST contains no hosts; refusing to start" >&2
    exit 1
fi

cat > "$CONF" <<CONF
# Generated by proxy-entrypoint.sh. Edits here are lost on restart; the
# allowlist is $ALLOWLIST.

http_port $PORT

# --- what a build may ask for ------------------------------------------------
acl docup_allowed dstdomain$HOSTS
acl CONNECT method CONNECT
acl TLS_port port 443

# 🛑 Destinations that are never legitimate, denied FIRST and by address
# rather than by name. An allowlisted hostname whose DNS answer is a private
# or link-local address is the DNS-rebinding shape §8.3.9 already refuses for
# the application's own egress; squid resolves the name itself, so the same
# refusal has to exist here or the allowlist becomes a way to reach the host
# network through a name somebody else controls.
acl docup_forbidden_dst dst 0.0.0.0/8
acl docup_forbidden_dst dst 10.0.0.0/8
acl docup_forbidden_dst dst 100.64.0.0/10
acl docup_forbidden_dst dst 127.0.0.0/8
acl docup_forbidden_dst dst 169.254.0.0/16
acl docup_forbidden_dst dst 172.16.0.0/12
acl docup_forbidden_dst dst 192.168.0.0/16
acl docup_forbidden_dst dst ::1/128
acl docup_forbidden_dst dst fc00::/7
acl docup_forbidden_dst dst fe80::/10
http_access deny docup_forbidden_dst

# 🛑 CONNECT to 443 and nothing else. Not a narrowing of §8.5.9 but a
# reading of it: every host on the list serves HTTPS, plain-HTTP proxying
# would put the proxy in the middle of content it must not see or alter, and
# CONNECT to any other port turns the allowlist into a port scanner for
# whatever an allowlisted name resolves to.
http_access deny CONNECT !TLS_port
http_access deny !CONNECT

http_access allow docup_allowed
http_access deny all

# 🛑 NO ssl_bump, NO sslproxy_cert_sign, NO http_port ... ssl-bump anywhere in
# this file. §8.5.9: "TLS MUST NOT be intercepted." A bumping proxy would see
# every token a build sends to a package index, and an installation-wide CA
# in every build image is a worse artefact than anything it would catch.

# 🛑 §8.5.20: "A dependency or package cache MUST NOT be shared *writably*
# between builds." A caching forward proxy is exactly that shared cache, and
# a poisoned entry would be served to every later build on the installation.
# Operators who want a mirror get a read-only one, which is a different thing.
cache deny all
cache_mem 0 MB

# One line per request, to stdout, so the runner can attribute a refusal to
# the build that caused it (§8.5.15's "specific user-facing message"): the
# client address is the build's network-namespace warden, which the runner
# created and therefore knows.
logformat docup %ts.%03tu %>a %Ss/%03>Hs %rm %ru
access_log stdio:/dev/stdout docup
cache_log stdio:/dev/stderr
pid_filename none

# Nothing about this installation travels to the origin.
via off
forwarded_for delete
httpd_suppress_version_string on

dns_v4_first on
shutdown_lifetime 3 seconds
CONF

echo "docup-proxy: allowlisted$HOSTS" >&2

exec squid -N -f "$CONF" "$@"
