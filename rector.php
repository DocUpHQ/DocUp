declare(strict_types=1);

use Rector\Config\RectorConfig;
use Rector\Set\ValueObject\SetList;

/*
| Rector is run deliberately, never automatically.
|
| SPEC 9.4 lists it in the baseline toolchain, but a tool that rewrites code
| does not belong in a gate that must pass before a commit: a gate tells you
| something is wrong, and Rector changes the thing. It is run at phase
| boundaries, its diff is read, and its output goes through the same review as
| hand-written code.
|
|   vendor/bin/rector process --dry-run    # read the diff
|   vendor/bin/rector process              # apply, then run the gate
*/

return RectorConfig::configure()
    ->withPaths([
        __DIR__.'/app',
        __DIR__.'/config',
        __DIR__.'/database',
        __DIR__.'/routes',
        __DIR__.'/tests',
    ])
    ->withSkip([
        __DIR__.'/bootstrap/cache',
        __DIR__.'/vendor',
        // Generated by their builders; the mutation is the reviewable artefact.
        __DIR__.'/tests/Fixtures/AbuseCorpus/_generated',
    ])
    // ADR 0007: the floor is PHP 8.4.1, so 8.4 is the highest level that may be
    // targeted. Raising this to 8.5 would emit code the support matrix forbids.
    ->withPhpSets(php84: true)
    ->withSets([
        SetList::CODE_QUALITY,
        SetList::DEAD_CODE,
        SetList::TYPE_DECLARATION,
        SetList::EARLY_RETURN,
    ])
    ->withImportNames(importShortClasses: false)
    ->withTypeCoverageLevel(0)
    ->withDeadCodeLevel(0)
    ->withCodeQualityLevel(0);
