declare(strict_types=1);

namespace App\Search;

use App\Access\AccessSurface;
use App\Access\ReaderContext;
use App\Access\ReaderGate;
use App\Auth\AccessLevel;
use App\Auth\OrganisationContext;
use App\Serving\SnapshotMount;
use App\Serving\SnapshotVersion;
use App\Support\Uuid;
use Illuminate\Support\Facades\DB;

/**
 * 🛑 §8.16.6's "server-side only", and §8.12.21's gate, in one place.
 *
 * > §8.16.6: "Visibility filters MUST be applied **server-side only**, derived
 * > from project authorisation, version visibility and each matched mount's
 * > `min_access`."
 *
 * This is the only class that turns a reader into a set of documents they may
 * search. Everything downstream — both engines, the URL computation, whatever
 * Phase 30 builds on top — receives an {@see AuthorisedScope} and can only
 * narrow it.
 *
 * ## 🛑 One decision per version, through the one function
 *
 * A project is not one access answer. §8.2.10 lets a public project hold a
 * `members` version, and §8.16.9 puts up to three versions in the index — so a
 * single `authorise()` call for the version the reader happens to be on would
 * leak the others or hide them, depending which way it went.
 *
 * So there is a loop, and every iteration calls `ReaderGate::authorise()` with
 * `AccessSurface::Search`. That is the same shape `AddonsController` uses for
 * §8.12.9's flyout and for the same reason: the surfaces that are "generated
 * from the **authorised** view" are generated by asking, per row, the one
 * function that is allowed to answer. The cached `scope` column on the row is
 * **not** consulted for the decision — it exists so the SQL is narrow (§8.16.6's
 * measured 80 ms) and {@see ScopeLevel} says so at length.
 *
 * ## 🛑 Why the gate is checked before the loop and not inside it
 *
 * §8.12.21's generation gate is a property of the **project**, not of a
 * version: it says the project's whole index is untrustworthy. Checking it once
 * and returning {@see AuthorisedScope::gated()} means a gated project produces
 * one decision record rather than one per version, and it means the caller can
 * tell "search is disabled" from "nothing matched" — which §8.12.21 makes a
 * different fact, and conflating them is how a disabled index gets reported as
 * an empty corpus for a week.
 *
 * 🛑 And the project-level call is made **only in the refusing case**. The
 * first version of this class asked it unconditionally, as a project-level
 * question about an "anchor" version — and that was a defect: `authorise()`
 * evaluates the whole §12.3 lattice, so a project whose first exposed version
 * happened to be `members` denied the anchor and the whole scope came back
 * empty. An anonymous reader then found **nothing at all**, including the
 * public versions, and the test that caught it was the one asserting the
 * public version was still searchable in the same breath as the private one.
 *
 * Written down because the empty result looked exactly like the filter working.
 */
final readonly class SearchScopes
{
    /**
     * 🛑 The most scope rows read for one query.
     *
     * §8.16.9 caps the index at three versions per project, and a version has
     * as many mounts as it has components — so a project's own scope set is
     * small by construction. The cap is here for §8.16.12's `self:me` and for
     * a composition nobody anticipated, and it is a **read** cap rather than a
     * truncation of an authorised set: the rows are ordered deterministically
     * so that two identical queries see the same set, and §8.16.10's
     * cross-project search is Phase 30's deliverable and owns the design for an
     * accessible set this size.
     */
    public const int MAX_SCOPE_ROWS = 500;

    public function __construct(
        private ReaderGate $gate,
        private OrganisationContext $context,
    ) {}

    /**
     * What this reader may search within the resolved project.
     *
     * @param  SnapshotMount  $mount  the resolved mount, which is what carries
     *                                the per-host `mount_exposure` §12.3
     *                                narrows by — and the reason the stored
     *                                `scope` column cannot be the decision: it
     *                                is host-independent by design, because the
     *                                index is per project and a project may be
     *                                mounted on several hosts with different
     *                                exposures
     * @param  list<ScopeRequest>  $requests  §8.16.12's scope filters, which may
     *                                        only narrow
     */
    public function forMount(
        SnapshotMount $mount,
        ?ReaderContext $reader = null,
        array $requests = [],
    ): AuthorisedScope {
        $project = $mount->project;
        $generations = SearchGenerations::forProject($project->id);

        if (! $generations->isIndexed()) {
            return AuthorisedScope::nothing();
        }

        /*
         * 🛑 §8.12.21's gate, and it is asked **only when it refuses**.
         *
         * The comparison itself is two integers from one row
         * ({@see SearchGenerations}). What `EffectiveAccess` adds is the
         * refusal: one reason code, `AccessReason::SearchGenerationStale`, and
         * one §20.3 decision record naming it. That call is made here so the
         * refusal comes from the one function rather than from this class
         * inventing a second denial — and it is made only in the refusing case
         * because in the allowing case it would be a decision about a version
         * nobody asked about, logged on every search.
         *
         * 🛑 The gate sits **before** the lattice inside the function (its own
         * comment says why), so the anchor version's visibility cannot change
         * the answer: a gated project refuses with
         * `SearchGenerationStale` whether the anchor is public or private.
         * That is what makes one call enough.
         *
         * Every per-version decision below still carries `searchGeneration`, so
         * the gate is a property of every search decision and not of this
         * branch.
         */
        if ($generations->lagsPolicy()) {
            $anchor = $this->anchorVersion($mount);

            if ($anchor instanceof SnapshotVersion) {
                $this->gate->authorise(
                    mount: $mount,
                    version: $anchor,
                    language: $anchor->language,
                    path: '',
                    surface: AccessSurface::Search,
                    reader: $reader,
                    searchGeneration: $generations->searchPolicyGeneration,
                );
            }

            return AuthorisedScope::gated();
        }

        /*
         * 🛑 A `collection:` request narrows to **nothing** in this phase.
         *
         * §8.16.12 requires the filter to parse — it is part of the minimum
         * syntax every driver honours — and §8.16.10's cross-project search
         * within a collection is §17's Phase 30 deliverable. Ignoring the
         * request and searching the resolved project anyway would be the worst
         * of the three options: the reader asked to search a collection, got
         * one project's results, and has no way to tell.
         *
         * Narrowing to nothing is the honest answer and the non-disclosing one
         * — an empty result is indistinguishable from "that collection has
         * nothing matching", so it reveals no collection's existence either.
         * The abuse corpus carries it as `search-012`.
         */
        foreach ($requests as $request) {
            if ($request->kind === ScopeKind::Collection) {
                return AuthorisedScope::nothing();
            }
        }

        $projectRequests = $this->projectRequests($requests);
        $accessibleOnly = $this->wantsAccessibleSet($requests);

        if ($projectRequests !== [] && ! $this->requestsThisProject($projectRequests, $mount)) {
            /*
             * 🛑 A `project:` filter naming something other than the resolved
             * project narrows to nothing, and does **not** reach across to
             * another project.
             *
             * §8.16.10's cross-project search within a collection is Phase 30's
             * deliverable. Until it exists, honouring `project:other` would
             * mean this phase quietly shipping cross-project search with none
             * of the collection-membership checks that requirement describes —
             * and an empty result is indistinguishable from "that project has
             * nothing matching", which is the non-disclosing answer.
             */
            return AuthorisedScope::nothing();
        }

        $versionFilter = $this->versionFilter($projectRequests);

        $facts = [];

        foreach ($this->rowsFor($project->id, $generations->searchGeneration) as $row) {
            if ($versionFilter !== null && $row['version_slug'] !== $versionFilter) {
                continue;
            }

            $version = $this->versionIn($mount, $row['version_id']);

            if (! $version instanceof SnapshotVersion) {
                /*
                 * A scope row for a version the snapshot does not expose on
                 * this host — a mount whose `paths` do not include the slug, or
                 * a version deleted since the last pass. Absent from the
                 * snapshot means absent from this host, and §8.9.3's "MUST
                 * NEVER fall through" reasoning applies: not exposed here is
                 * not searchable here.
                 */
                continue;
            }

            $decision = $this->gate->authorise(
                mount: $mount,
                version: $version,
                language: $version->language,
                /*
                 * The version root, exactly as `AddonsController` does for the
                 * flyout and for the reason it states: the question is whether
                 * this reader may be told this version's content exists, and
                 * §8.12.9 makes path-scoped rules best-effort for a derived
                 * surface. A per-hit path check would be a second decision per
                 * result and would still be asking about a path the reader has
                 * not requested.
                 */
                path: '',
                surface: AccessSurface::Search,
                componentMinAccess: $row['min_access'],
                reader: $reader,
                searchGeneration: $generations->searchPolicyGeneration,
            );

            if (! $decision->allowed) {
                continue;
            }

            $facts[] = new ScopeFact(
                projectId: $project->id,
                projectSlug: $row['project_slug'],
                versionId: $row['version_id'],
                versionSlug: $row['version_slug'],
                /*
                 * 🛑 The **snapshot's** manifest id, not the one the scope
                 * query joined. §8.16.5 computes result URLs "at query time
                 * from the manifest's mount table", and the snapshot is loaded
                 * per request — so a version that republished since the last
                 * indexing pass contributes its new mount table and the URL is
                 * right. Reading it from the join would have been a second
                 * source for one fact, which is the failure Phase 28 recorded
                 * three times over.
                 */
                manifestId: $version->publishedManifestId,
                buildId: $row['build_id'],
                buildGeneration: $row['build_generation'],
                language: $row['language'],
                scope: ScopeLevel::fromStored($row['scope']),
                minAccess: $row['min_access'],
                channel: $row['channel'],
            );
        }

        if ($accessibleOnly && $facts === []) {
            /*
             * `self:me` over a reader with nothing accessible. The same empty
             * answer, reached by the same route — recorded here only because
             * the flag is otherwise unused and a reader of this code will look
             * for where it goes.
             */
            return AuthorisedScope::nothing();
        }

        return new AuthorisedScope($facts);
    }

    /**
     * The live scope rows for one project.
     *
     * 🛑 Read **across organisations**, with the tenant decided by the host.
     * `ManifestReader::loadMounts()` states the reason this pattern is correct
     * on the serving path: "the reader has supplied a hostname and a path, and
     * the tenant was already decided by the host. Re-deriving it here would be
     * a second answer to a settled question, and two answers is how they
     * disagree." The `project_id` predicate is what scopes the read, and it
     * came from the routing snapshot.
     *
     * @return list<array{project_slug: string, version_id: string, version_slug: string, build_id: string, build_generation: int, language: string, scope: string, min_access: AccessLevel|null, channel: string}>
     */
    private function rowsFor(string $projectId, int $generation): array
    {
        /** @var list<array{project_slug: string, version_id: string, version_slug: string, build_id: string, build_generation: int, language: string, scope: string, min_access: AccessLevel|null, channel: string}> */
        return $this->context->acrossAllOrganisations(function () use ($projectId, $generation): array {
            $rows = DB::table('search_mount_scopes as s')
                ->join('projects as p', 'p.id', '=', 's.project_id')
                ->join('project_versions as v', 'v.id', '=', 's.project_version_id')
                ->where('s.project_id', $projectId)
                ->where('s.generation', $generation)
                ->orderBy('s.project_version_id')
                ->orderBy('s.build_id')
                ->limit(self::MAX_SCOPE_ROWS)
                ->get([
                    'p.slug as project_slug',
                    'v.id as version_id',
                    'v.slug as version_slug',
                    's.build_id',
                    's.build_generation',
                    's.language',
                    's.scope',
                    's.min_access',
                    's.channel',
                ]);

            $out = [];

            foreach ($rows as $row) {
                if (! is_string($row->build_id) || ! Uuid::isBytes($row->build_id)) {
                    continue;
                }

                $out[] = [
                    'project_slug' => is_string($row->project_slug) ? $row->project_slug : '',
                    'version_id' => is_string($row->version_id) ? $row->version_id : '',
                    'version_slug' => is_string($row->version_slug) ? $row->version_slug : '',
                    'build_id' => Uuid::toText($row->build_id),
                    'build_generation' => (int) $row->build_generation,
                    'language' => is_string($row->language) ? $row->language : 'en',
                    'scope' => is_string($row->scope) ? $row->scope : '',
                    'min_access' => is_string($row->min_access) ? ScopeLevel::fromStored($row->min_access) : null,
                    'channel' => is_string($row->channel) ? $row->channel : 'default',
                ];
            }

            return $out;
        });
    }

    /**
     * The version the gate's project-level question is asked about.
     *
     * The mount's default version where it has one, else the first version the
     * snapshot exposes. Any of them gives the same answer to §8.12.21's gate,
     * which is about the project — so the choice only has to be deterministic.
     */
    private function anchorVersion(SnapshotMount $mount): ?SnapshotVersion
    {
        foreach ($mount->project->versions as $version) {
            if ($mount->exposes($version->slug)) {
                return $version;
            }
        }

        return null;
    }

    /** One version out of the snapshot, by raw id. */
    private function versionIn(SnapshotMount $mount, string $versionId): ?SnapshotVersion
    {
        foreach ($mount->project->versions as $version) {
            if ($version->id === $versionId && $mount->exposes($version->slug)) {
                return $version;
            }
        }

        return null;
    }

    /**
     * @param  list<ScopeRequest>  $requests
     * @return list<ScopeRequest>
     */
    private function projectRequests(array $requests): array
    {
        return array_values(array_filter(
            $requests,
            static fn (ScopeRequest $request): bool => $request->kind === ScopeKind::Project,
        ));
    }

    /** @param  list<ScopeRequest>  $requests */
    private function wantsAccessibleSet(array $requests): bool
    {
        foreach ($requests as $request) {
            if ($request->kind === ScopeKind::Accessible) {
                return true;
            }
        }

        return false;
    }

    /**
     * Whether a `project:` request names the resolved project.
     *
     * Compared against the snapshot's slug, which came from the database and
     * not from the request. `QueryParser::slug()` has already reduced the
     * requested value to `[a-z0-9._-]`, so this is a comparison of two narrowed
     * strings rather than a pattern match.
     *
     * @param  list<ScopeRequest>  $requests
     */
    private function requestsThisProject(array $requests, SnapshotMount $mount): bool
    {
        foreach ($requests as $request) {
            if ($request->slug === $mount->project->slug) {
                return true;
            }
        }

        return false;
    }

    /**
     * The `/<version>` half of `project:<slug>/<version>`, or null.
     *
     * @param  list<ScopeRequest>  $requests
     */
    private function versionFilter(array $requests): ?string
    {
        foreach ($requests as $request) {
            if ($request->version !== null && $request->version !== '') {
                return $request->version;
            }
        }

        return null;
    }
}
