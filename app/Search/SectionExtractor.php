declare(strict_types=1);

namespace App\Search;

use Dom\Element;
use Dom\HTMLDocument;
use Dom\Node;
use Dom\Text;

/**
 * 🛑 §8.16.3's extraction: one document per heading anchor, out of somebody
 * else's HTML.
 *
 * > §8.16.3: "One search document per HTML **section** (heading anchor),
 * > extracted with main-content detection (`role="main"` → `<main>` → parent of
 * > the first `<h1>` → `<body>`), navigation/script/anchor-link stripping,
 * > nested title and content boosts, and a −10…+10 per-page rank honouring
 * > `search.ranking` and `search.ignore` from §8.4.2."
 *
 * ## 🛑 This parses a document, and §8.15.3 forbade exactly that. Why it is different here
 *
 * Phase 28's `ChromeInjector` is a **byte-level** search with no parser, and
 * §8.15.3 states the reason: "a parser normalises a document, and normalising
 * attacker-supplied markup changes what a browser renders in ways nobody
 * reviewed". That prohibition is about **the bytes that get served**. The
 * injector's output is the document readers download, so a normalisation there
 * changes what they see.
 *
 * Nothing here is ever served. This reads a document and writes *text into a
 * database*; the stored artifact is untouched and §4.3/2's "documentation bytes
 * never traverse PHP" is a serving-path invariant that indexing is explicitly
 * outside of — §8.16.3 could not be implemented at all otherwise, since "one
 * document per heading anchor" needs to know where the headings are.
 *
 * So a real HTML5 parser is correct here and a regex would not be: the input is
 * generated by ten unrelated tools, and `<h2 id="a">` is the *easy* case.
 *
 * ## 🛑 What is stripped, and why each one
 *
 * - **`<script>`, `<style>`, `<template>`, `<noscript>`** — §8.16.3 names
 *   script. `style` is included because its text is CSS, and CSS contains every
 *   term in a theme's selector names: without it, `nav` and `sidebar` match
 *   every page on a Sphinx site. `template` and `noscript` hold markup that was
 *   never rendered, so indexing it returns results for text no reader can see.
 * - **Navigation** — `<nav>`, `[role="navigation"]`, and the generators' own
 *   containers. This is the one that decides whether search is usable: a
 *   Sphinx sidebar repeats the whole table of contents on **every** page, so
 *   without stripping it every page matches every page's title, and the top
 *   result for any term is whichever page the relevance sort happened to pick.
 * - **Anchor links** — the `¶` and `#` permalinks generators append to every
 *   heading. Left in, every indexed title ends in a pilcrow and the stored
 *   title is what the result list shows the reader.
 *
 * 🛑 Stripping is **by element**, never by class-name heuristic beyond the
 * documented generator list. A guess that removed a project's real content
 * would make pages unfindable with no error anywhere, which is the worst
 * failure shape this class has: the index would simply be quietly incomplete.
 */
final readonly class SectionExtractor
{
    /**
     * 🛑 Bumped whenever extraction's **output** changes for the same input.
     *
     * `ChromeInjector::VERSION` exists for the same reason and Phase 28 needed
     * it within the week. The number is stored on every document, so an
     * operator can see which rows predate a change and
     * `docup:search-index --force` can be told to re-extract only those.
     */
    public const int VERSION = 1;

    /**
     * 🛑 The largest document parsed, in bytes.
     *
     * §9.2 budgets "search indexer peak memory: bounded and declared per
     * driver", and a DOM is roughly an order of magnitude larger than the bytes
     * it came from — so one pathological page decides the whole indexer's peak.
     * 8 MiB of HTML is already far beyond any hand-written page; what reaches
     * it is a generated API reference or a `singlehtml` build, and those are
     * **skipped with a reason** rather than allowed to decide the budget.
     *
     * Skipping loses search for that page. That is the honest trade and
     * {@see ExtractionReport} surfaces it per build so an operator sees which
     * page rather than wondering why it is unfindable.
     */
    public const int MAX_DOCUMENT_BYTES = 8 * 1024 * 1024;

    /** The longest stored section body, in characters. */
    public const int MAX_CONTENT_CHARS = 20_000;

    /**
     * 🛑 How far {@see self::anchorOf()} looks up for an `id`.
     *
     * Three, because Sphinx's `<section id="x"><h2>` is one hop and Furo's
     * extra wrapper is two. An unbounded walk always finds *something* — the
     * `<div id="content">` every theme has — and a link to `#content` is a link
     * to the top of the page wearing a fragment, which looks like a working
     * deep link and is not.
     */
    private const int MAX_ANCHOR_DEPTH = 3;

    /**
     * Elements whose text is never content.
     *
     * Lower-case local names; the parser normalises case for HTML elements.
     */
    private const array DROPPED_ELEMENTS = [
        'script', 'style', 'template', 'noscript', 'svg', 'math', 'iframe', 'object',
        'nav', 'form', 'button', 'select', 'textarea', 'dialog',
    ];

    /**
     * The generators' own navigation containers, by class or id.
     *
     * 🛑 A **named** list with the generator beside each entry, not a pattern.
     * `*sidebar*` would also catch a project's own `#sidebar-notes` and silently
     * drop its content; these are the exact hooks the five generators DocUp
     * supports actually emit.
     */
    private const array NAVIGATION_HOOKS = [
        // Sphinx: classic themes and Furo.
        'sphinxsidebar',
        'sphinxsidebarwrapper',
        'related',
        'relations',
        'toctree-wrapper',
        'sidebar-drawer',
        'toc-drawer',
        // Read the Docs' Sphinx theme.
        'wy-nav-side',
        'wy-breadcrumbs',
        'rst-footer-buttons',
        // MkDocs and Material.
        'md-sidebar',
        'md-header',
        'md-footer',
        'md-tabs',
        'md-nav',
        'md-skip',
        // Docusaurus.
        'theme-doc-sidebar-container',
        'theme-doc-toc-desktop',
        'theme-doc-toc-mobile',
        'pagination-nav',
        'theme-doc-breadcrumbs',
        // Antora.
        'nav-container',
        'toc',
        'toolbar',
        // mdBook.
        'sidebar',
        'nav-wrapper',
        'nav-wide-wrapper',
        'nav-chapters',
    ];

    /**
     * Permalink anchors appended to headings.
     *
     * Sphinx emits `a.headerlink`, Material `a.headerlink`, Docusaurus
     * `a.hash-link`, Antora `a.anchor`, mdBook `a.header`. The `¶` and `#`
     * glyph is the visible part; the element is what carries it.
     */
    private const array PERMALINK_HOOKS = [
        'headerlink',
        'hash-link',
        'anchor',
        'anchorjs-link',
        'permalink',
        'toc-backref',
    ];

    /**
     * Extract one page.
     *
     * @param  string  $path  relative to the build's `html/` root, e.g.
     *                        `guide/index.html` — §8.16.5's key, and the value
     *                        `search.ranking` patterns are matched against
     * @param  string  $html  the stored bytes, exactly as served
     * @return list<Section> in document order; empty when the page is ignored,
     *                       oversized or holds no text
     */
    public function extract(string $path, string $html, SearchRanking $ranking): array
    {
        if ($ranking->ignores($path)) {
            return [];
        }

        if ($html === '' || strlen($html) > self::MAX_DOCUMENT_BYTES) {
            return [];
        }

        $document = $this->parse($html);

        if (! $document instanceof HTMLDocument) {
            return [];
        }

        $root = $this->mainContent($document);

        if (! $root instanceof Element) {
            return [];
        }

        $this->strip($root);

        $pageTitle = $this->pageTitle($document, $root);
        $rank = $ranking->rankFor($path);

        return $this->sectionsIn($root, $path, $pageTitle, $rank);
    }

    /**
     * Extract from a content **fragment** that is already known to be the
     * content — §8.16.4's Sphinx route.
     *
     * 🛑 No main-content detection, deliberately: a `.fjson`'s `body` is the
     * page's content with no theme around it, so running the heuristic over it
     * would be asking a guess about something already known. The stripping
     * still runs, because a content fragment can legitimately hold a
     * `<script>` for a MathJax block or a permalink anchor Sphinx appended to
     * every heading.
     *
     * @param  string  $path  build-relative, as {@see self::extract()}
     * @param  string  $title  the page title the generator reported, which is
     *                         better than anything a fragment can tell us — a
     *                         fragment often has no `h1` at all, because the
     *                         theme renders it from the document's metadata
     * @return list<Section>
     */
    public function fragment(string $path, string $fragment, SearchRanking $ranking, string $title = ''): array
    {
        if ($ranking->ignores($path)) {
            return [];
        }

        if ($fragment === '' || strlen($fragment) > self::MAX_DOCUMENT_BYTES) {
            return [];
        }

        /*
         * Wrapped in a minimal document because the HTML5 parser parses
         * documents, not fragments — `createFromString` on a bare
         * `<section>…</section>` yields the same tree, but only because the
         * parser inserts the implied `html`, `head` and `body` itself. Writing
         * the wrapper makes that explicit rather than relying on it, and the
         * `<main>` is what `mainContent()` would have found anyway.
         */
        $document = $this->parse(
            '<!DOCTYPE html><html><head><meta charset="utf-8"></head><body><main>'
            .$fragment
            .'</main></body></html>',
        );

        if (! $document instanceof HTMLDocument) {
            return [];
        }

        $root = $document->querySelector('main');

        if (! $root instanceof Element) {
            return [];
        }

        $this->strip($root);

        $pageTitle = $title !== '' ? $this->cap($title, 500) : $this->pageTitle($document, $root);

        return $this->sectionsIn($root, $path, $pageTitle, $ranking->rankFor($path));
    }

    /**
     * Parse, or null.
     *
     * 🛑 `Dom\HTMLDocument` and not `DOMDocument::loadHTML`. The legacy parser
     * is libxml's HTML **4** parser: it does not know HTML5's content model, it
     * relocates `<main>` and `<section>` unpredictably, and it needs a `<meta
     * charset>` hint or it guesses ISO-8859-1 and mangles every non-ASCII
     * heading. The input here is generated by ten tools DocUp does not control,
     * so the parser has to be the one the browsers' own specification describes.
     *
     * 🛑 **`LIBXML_NOERROR` is the only flag passed, and the XML parser's flags
     * are not accepted here at all.**
     *
     * Measured on PHP 8.5: `createFromString()` accepts exactly
     * `LIBXML_NOERROR`, `LIBXML_COMPACT`, `LIBXML_HTML_NOIMPLIED` and
     * `Dom\HTML_NO_DEFAULT_NS`, and **throws `ValueError`** for anything else.
     * The first version of this method passed `LIBXML_NONET | LIBXML_NOENT` as
     * belt and braces against XXE — which made every single document
     * unparseable, silently, because the `ValueError` was caught below and
     * turned into "this page has no sections".
     *
     * Those flags are not merely unnecessary, they are meaningless here: the
     * HTML5 parser has no DTD subset and resolves **no** external entities, so
     * XXE is not a property it can have. The XML parser is where that defence
     * belongs, and the XML parser is what this class deliberately does not use.
     * Recorded in §14.3's trap list.
     *
     * 🛑 And `ValueError` is **not** caught any more. A rejected flag is a bug
     * in DocUp, not a hostile document, and swallowing it cost an afternoon:
     * sixteen tests failed with an empty result and the failure named the
     * assertion rather than the cause. A hostile document is still handled —
     * that is what the `Throwable` catch is for — but a programming error now
     * escapes loudly.
     */
    private function parse(string $html): ?HTMLDocument
    {
        try {
            return HTMLDocument::createFromString($html, LIBXML_NOERROR, 'UTF-8');
        } catch (\ValueError $invalid) {
            throw $invalid;
        } catch (\Throwable) {
            /*
             * A document the HTML5 parser refuses is a document no browser
             * renders either. Returning null makes the page unindexed rather
             * than failing the build's whole indexing pass — one unparseable
             * file must not cost a project its search.
             */
            return null;
        }
    }

    /**
     * 🛑 §8.16.3's main-content detection, in its stated order.
     *
     * `role="main"` → `<main>` → the parent of the first `<h1>` → `<body>`.
     *
     * The order is not arbitrary and is worth keeping exactly: `role="main"` is
     * what Sphinx's and Read the Docs' themes emit and what a theme author sets
     * deliberately, so it wins over a `<main>` that a layout wrapper might also
     * carry. The `<h1>`'s parent is the fallback for themes that mark nothing —
     * mdBook and some Docusaurus versions — and it works because a generated
     * page's `<h1>` is inside the content and the sidebar's titles are not
     * `<h1>`s. `<body>` is last and indexes the navigation along with
     * everything else, which is why the strip list exists.
     */
    private function mainContent(HTMLDocument $document): ?Element
    {
        $byRole = $document->querySelector('[role="main"]');

        if ($byRole instanceof Element) {
            return $byRole;
        }

        $main = $document->querySelector('main');

        if ($main instanceof Element) {
            return $main;
        }

        $h1 = $document->querySelector('h1');

        if ($h1 instanceof Element && $h1->parentElement instanceof Element) {
            return $h1->parentElement;
        }

        $body = $document->querySelector('body');

        return $body instanceof Element ? $body : null;
    }

    /**
     * Remove everything whose text is not content.
     *
     * Collected first and removed afterwards: removing while walking a live
     * `NodeList` skips siblings, which is the classic DOM bug and here it would
     * leave half a sidebar in the index.
     */
    private function strip(Element $root): void
    {
        $doomed = [];

        foreach (self::DROPPED_ELEMENTS as $name) {
            foreach ($root->querySelectorAll($name) as $node) {
                $doomed[] = $node;
            }
        }

        foreach (self::NAVIGATION_HOOKS as $hook) {
            foreach ($root->querySelectorAll('.'.$hook) as $node) {
                $doomed[] = $node;
            }

            foreach ($root->querySelectorAll('#'.$hook) as $node) {
                $doomed[] = $node;
            }
        }

        foreach (self::PERMALINK_HOOKS as $hook) {
            foreach ($root->querySelectorAll('a.'.$hook) as $node) {
                $doomed[] = $node;
            }
        }

        /*
         * ARIA navigation landmarks, and `aria-hidden` subtrees.
         *
         * 🛑 `aria-hidden="true"` is what a theme puts on a decorative glyph —
         * the pilcrow, a chevron, an icon font's private-use character. A
         * screen reader is told to skip it and so is the index, for the same
         * reason: it is not text, and in an icon font it is not even a
         * character a reader could type.
         */
        foreach (['[role="navigation"]', '[role="search"]', '[role="banner"]', '[aria-hidden="true"]'] as $selector) {
            foreach ($root->querySelectorAll($selector) as $node) {
                $doomed[] = $node;
            }
        }

        foreach ($doomed as $node) {
            /*
             * A node may appear twice — a `<nav class="md-nav">` is in both the
             * element list and the hook list — and may already have left with
             * its parent. `parentNode` is the check that covers both.
             */
            $node->parentNode?->removeChild($node);
        }
    }

    /**
     * The page's own title.
     *
     * The first `<h1>` in the main content, because that is what the reader
     * sees at the top of the page; `<title>` only if there is none, because a
     * generator's `<title>` is usually `Page — Project vX` and the suffix is
     * noise repeated on every result.
     */
    private function pageTitle(HTMLDocument $document, Element $root): string
    {
        $h1 = $root->querySelector('h1');

        if ($h1 instanceof Element) {
            $text = $this->textOf($h1);

            if ($text !== '') {
                return $this->cap($text, 500);
            }
        }

        $title = $document->querySelector('title');

        return $title instanceof Element ? $this->cap($this->textOf($title), 500) : '';
    }

    /**
     * Walk the content in document order, cutting at every heading.
     *
     * 🛑 **Document order, iteratively.** A recursive walk over a
     * `singlehtml` Sphinx build — one file, every page, headings nested six
     * deep inside sections nested as deeply — is how an indexer meets PHP's
     * stack limit on a real project. The explicit stack is bounded by the
     * document's depth and costs nothing on a normal page.
     *
     * The content of a section is everything between its heading and the next
     * heading **of any level**, which is what a reader sees as "under this
     * heading". A deeper heading therefore ends its parent's body — correct,
     * because the parent's prose really did stop there, and the parent's own
     * document still carries its title and its nested title for §8.16.3's
     * boosts.
     *
     * @return list<Section>
     */
    private function sectionsIn(Element $root, string $path, string $pageTitle, int $rank): array
    {
        /**
         * The heading stack: level => text, for §8.16.3's nested title.
         *
         * @var array<int, string> $ancestry
         */
        $ancestry = [];

        $sections = [];
        $position = 0;

        /*
         * The page-level section: text before the first heading. It carries the
         * page title as its own title and a null anchor, because there is no
         * heading to link to — §8.16.5's `path` with no fragment is exactly the
         * page's own URL.
         */
        $current = new MutableSection(
            anchor: null,
            title: $pageTitle,
            headingPath: '',
            position: 0,
        );

        /** @var list<Node> $stack */
        $stack = [];

        for ($child = $root->lastChild; $child !== null; $child = $child->previousSibling) {
            $stack[] = $child;
        }

        while ($stack !== []) {
            $node = array_pop($stack);

            if ($node instanceof Text) {
                $current->append($node->data);

                continue;
            }

            if (! $node instanceof Element) {
                continue;
            }

            $level = $this->headingLevel($node);

            if ($level !== null) {
                $section = $current->toSection($path, $pageTitle, $rank);

                if ($section instanceof Section) {
                    $sections[] = $section;
                }

                $heading = $this->textOf($node);

                /*
                 * 🛑 Trim the stack to this heading's level BEFORE adding it, so
                 * an `h2` after an `h3` replaces rather than nests under it.
                 * Without this the nested title grows monotonically and a page
                 * with twenty headings ends with a 2 KB `heading_path` made of
                 * every heading that came before — which is both wrong and the
                 * reason the column has a length.
                 */
                foreach (array_keys($ancestry) as $existing) {
                    if ($existing >= $level) {
                        unset($ancestry[$existing]);
                    }
                }

                $trail = $ancestry;
                ksort($trail);

                $ancestry[$level] = $heading;

                $current = new MutableSection(
                    anchor: $this->anchorOf($node),
                    title: $heading,
                    headingPath: implode(Section::HEADING_SEPARATOR, $trail),
                    position: ++$position,
                );

                continue;
            }

            /*
             * Descend. Pushed in reverse so the children pop in document
             * order; a block element contributes a space so that
             * `<p>a</p><p>b</p>` is `a b` and not `ab`.
             */
            if ($this->isBlock($node)) {
                $current->append(' ');
            }

            for ($child = $node->lastChild; $child !== null; $child = $child->previousSibling) {
                $stack[] = $child;
            }
        }

        $section = $current->toSection($path, $pageTitle, $rank);

        if ($section instanceof Section) {
            $sections[] = $section;
        }

        return $this->withoutEmptyPreamble($sections);
    }

    /**
     * 🛑 Drop the page-level section when it holds no text of its own.
     *
     * A page whose content begins immediately with its `<h1>` — which is most
     * generated pages — has nothing before the first heading, so the page-level
     * section is minted with the page title as its title and an empty body. Two
     * documents then describe one heading: one anchored and one not, matching
     * the same terms, and the unanchored one sends the reader to the top of the
     * page instead of to the section. §8.16.3 asks for "one search document per
     * HTML **section** (heading anchor)" and that is not one.
     *
     * 🛑 Only when a heading section follows. A page with **no** headings at all
     * — a release-notes stub, a redirect page, a bare `<p>` — has the
     * page-level section as its only document, and dropping it would make the
     * page unsearchable. Likewise a page with a lead paragraph before its first
     * heading: that paragraph is real content and keeps its section.
     *
     * @param  list<Section>  $sections
     * @return list<Section>
     */
    private function withoutEmptyPreamble(array $sections): array
    {
        if (count($sections) < 2) {
            return $sections;
        }

        $first = $sections[0];

        if ($first->anchor === null && trim($first->content) === '') {
            return array_slice($sections, 1);
        }

        return $sections;
    }

    /** `h1`…`h6`, or null. */
    private function headingLevel(Element $element): ?int
    {
        $name = strtolower($element->localName);

        if (strlen($name) !== 2 || $name[0] !== 'h') {
            return null;
        }

        $level = (int) $name[1];

        return $level >= 1 && $level <= 6 ? $level : null;
    }

    /**
     * The anchor a result links to.
     *
     * The heading's own `id` when it has one, else the id of the nearest
     * ancestor that has one — which is where Sphinx puts it: `<div
     * class="section" id="installation"><h2>Installation</h2>`. Without the
     * ancestor fallback every Sphinx section would link to the page top, which
     * is the single most visible way a search result can be wrong.
     *
     * 🛑 Bounded by {@see self::MAX_ANCHOR_DEPTH} rather than walking to the
     * root; the constant says why.
     */
    private function anchorOf(Element $heading): ?string
    {
        $own = trim($heading->getAttribute('id') ?? '');

        if ($own !== '') {
            return $this->cap($own, 180);
        }

        $depth = 0;
        $parent = $heading->parentElement;

        while ($parent instanceof Element && $depth < self::MAX_ANCHOR_DEPTH) {
            $id = trim($parent->getAttribute('id') ?? '');

            if ($id !== '') {
                return $this->cap($id, 180);
            }

            $parent = $parent->parentElement;
            $depth++;
        }

        return null;
    }

    /**
     * Whether this element introduces a text break.
     *
     * Not the full CSS display list: what matters is that two adjacent blocks
     * do not run their words together. Inline elements are the ones that must
     * **not** break, because `an <code>api</code> token` is three words and
     * breaking inside it would store `an api token` as `an api token` either
     * way — while breaking inside `<em>auth</em>entication` would store two
     * words where the reader sees one.
     */
    private function isBlock(Element $element): bool
    {
        return ! in_array(strtolower($element->localName), [
            'a', 'abbr', 'b', 'bdi', 'bdo', 'cite', 'code', 'data', 'dfn', 'em',
            'i', 'kbd', 'mark', 'q', 'rp', 'rt', 'ruby', 's', 'samp', 'small',
            'span', 'strong', 'sub', 'sup', 'time', 'u', 'var', 'wbr',
        ], true);
    }

    /** An element's visible text, whitespace collapsed. */
    private function textOf(Element $element): string
    {
        return $this->collapse($element->textContent ?? '');
    }

    /** Collapse every run of whitespace, including the non-breaking kind. */
    private function collapse(string $text): string
    {
        $text = str_replace(["\u{00A0}", "\u{200B}", "\u{FEFF}"], ' ', $text);

        return trim((string) preg_replace('/\s+/u', ' ', $text));
    }

    /** Cap a string by characters, not bytes, so a cut never splits a glyph. */
    private function cap(string $text, int $chars): string
    {
        return mb_substr($this->collapse($text), 0, $chars);
    }
}
