declare(strict_types=1);

namespace App\Composition\SinglePass;

use App\Builds\Toolchain\ToolchainPlan;
use App\Composition\CompositionRefused;
use App\Composition\CompositionRejection;
use App\Config\DocupConfig;
use Symfony\Component\Yaml\Yaml;

/**
 * 🛑 §8.7.12's playbook, generated from the resolved plan.
 *
 * Antora is the generator §8.7.12 names first and the one §17's Phase 15
 * exit criterion tests, because it is the only one of the seven shipped
 * presets with a real multi-source model: a playbook lists content sources,
 * each source carries its own `antora.yml`, and `xref:` across them is a
 * first-class feature rather than a plugin.
 *
 * What this writes, and what it deliberately does not:
 *
 * - **`content.sources`** — one entry per contributing source, naming the
 *   **local checkout path** DocUp chose. Never a URL: §8.5.1 pins every
 *   contributing ref before any repository code runs, and a playbook that
 *   named a remote would fetch something nothing had pinned. The preset
 *   already refuses `--fetch` for the same reason.
 * - **`branches: HEAD`**, because the preset's `create_environment` makes
 *   each checkout a throwaway single-commit repository (Antora reads a git
 *   repository, not a directory) and `HEAD` is the only ref it has.
 * - **`site.start_page`**, from the **primary** component's `.docup.yaml`.
 *   §8.4.5 makes `html/index.html` mandatory and Antora writes nothing at
 *   the site root without one; §8.7.3 makes the primary mount the owner of
 *   "the root `index.html`, the fallback `404.html` and theme assets", so
 *   the primary component is the one entitled to say what the root is.
 * - **No `site.title`, no `site.url`, no mount path.** All three are
 *   project-scoped, and §8.7.10 does not stop applying because the mode
 *   changed. The title is chrome, which §8.15.1 injects at ingest and
 *   §8.7.13 records as serve-time in both modes.
 */
final readonly class AntoraPlaybook
{
    public const FILENAME = 'antora-playbook.yml';

    /**
     * Build the playbook.
     *
     * @param  list<SourceSlot>  $slots  every contributing source, primary first
     * @param  DocupConfig  $primary  the primary component's configuration, which
     *                                §8.7.3 makes the owner of the root
     *
     * @throws CompositionRefused when the primary names no start page
     */
    public function generate(array $slots, DocupConfig $primary, string $uiBundle): GeneratedComposition
    {
        $startPage = $primary->antoraStartPage();

        if ($startPage === null) {
            /*
             * 🛑 Refused, rather than guessed. Antora's start page is
             * `<component>::<page>`, and the component name lives in the
             * source's own `antora.yml` — which DocUp does not read, and
             * should not: §8.4.9 parses one configuration file outside the
             * sandbox under hard caps, and reading a second from every
             * contributing repository would widen that surface for a value
             * the author can state in one line.
             *
             * Guessing is worse than refusing here. Every wrong guess
             * produces a site whose front page is somebody else's section,
             * which looks deliberate.
             */
            throw CompositionRefused::of(
                CompositionRejection::SinglePassStartPageMissing,
                'the primary component must declare `antora: { start_page: … }` in .docup.yaml '
                    .'because Antora writes no site root without one (§8.4.5)',
            );
        }

        $sources = [];

        foreach ($slots as $slot) {
            $entry = [
                'url' => $slot->path(),

                // The throwaway repository the preset's `create_environment`
                // creates has exactly one branch, and this is it.
                'branches' => 'HEAD',
            ];

            $startPath = $slot->startPath();

            if ($startPath !== '') {
                $entry['start_path'] = $startPath;
            }

            $sources[] = $entry;
        }

        $playbook = [
            'site' => ['start_page' => $startPage],
            'content' => ['sources' => $sources],
            'ui' => ['bundle' => ['url' => $uiBundle, 'snapshot' => true]],
        ];

        return new GeneratedComposition(
            filename: self::FILENAME,
            contents: "# Generated by DocUp (§8.7.12) from the resolved plan.\n"
                ."# A contributing repository cannot add a source here: this file is\n"
                ."# written outside every checkout and is the only one Antora reads.\n"
                .Yaml::dump($playbook, 6, 2),
            prepare: $this->prepareCommands($slots),
        );
    }

    /**
     * 🛑 One throwaway git repository per checkout.
     *
     * Antora reads a git repository, not a directory, and §8.5.7 removes
     * `.git` before the build stage mounts the workspace — "a credential
     * cache waiting to be written to, a remote URL to exfiltrate to". The
     * `antora` preset has made one since Phase 09 for the single-source
     * case; `single_pass` needs one per slot, and the loop is here rather
     * than in the preset because the slot list is the plan's, not the
     * preset's.
     *
     * `SOURCE_DATE_EPOCH` is the preset's own, so the commit — and
     * therefore Antora's output — is identical on every build of the same
     * sources (§18.13).
     *
     * @param  list<SourceSlot>  $slots
     * @return list<string>
     */
    private function prepareCommands(array $slots): array
    {
        $commands = [];

        foreach ($slots as $slot) {
            $path = ToolchainPlan::quote($slot->path());

            $commands[] = 'if [ ! -d '.ToolchainPlan::quote($slot->path().'/.git').' ]; then '
                .'( cd '.$path.' '
                .'&& export GIT_AUTHOR_DATE="@${SOURCE_DATE_EPOCH} +0000" '
                .'&& export GIT_COMMITTER_DATE="@${SOURCE_DATE_EPOCH} +0000" '
                .'&& git init --quiet --initial-branch=main . '
                .'&& git -c user.email=build@docup.invalid -c user.name=DocUp add --all '
                .'&& git -c user.email=build@docup.invalid -c user.name=DocUp '
                .'commit --quiet --no-gpg-sign -m "DocUp build snapshot" ); fi';
        }

        return $commands;
    }
}
