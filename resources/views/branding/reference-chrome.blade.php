{{--
    🛑 §8.14.14's reference example theme, rendered.

    > "A versioned `chrome_mode: api_only` contract with a **reference example
    > theme** MUST ship, as the first-class answer to 'can we ship our own
    > chrome?'. 'Tokens only' loses deals."

    This is the worked example: every field of the `api_only` payload, rendered
    as the chrome an integrator would build from it. It is generated by
    `php artisan docup:branding-reference` and it is the page `npm run axe`
    checks, so §9.5's "axe reporting zero violations in CI" is asserted against
    markup DocUp actually produces rather than against a hand-written fixture.

    🛑 Every accessibility decision here is load-bearing and each is noted where
    it is made, because an integrator copying this file is copying those
    decisions too — which is the point of shipping a reference rather than a
    schema.
--}}
<!DOCTYPE html>
<html lang="{{ $lang }}" @if($scheme !== 'system') data-docup-scheme="{{ $scheme }}" @endif>
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{{ $brand }} — documentation</title>
    @if($favicon !== null)
        <link rel="icon" href="{{ $favicon }}">
    @endif
    {{--
        🛑 The theme stylesheet, content-addressed (§8.14.4). Inlined here
        rather than linked because this file is generated for a static
        accessibility check and jsdom does not fetch; a real consumer links it.
    --}}
    <style>{!! $stylesheet !!}</style>
    <style>{!! $chromeCss !!}</style>
</head>
<body>
    {{--
        🛑 A skip link, first in the document and visible on focus. WCAG 2.2
        SC 2.4.1: a reader using the keyboard must be able to reach the content
        without walking the navigation on every page.
    --}}
    <a class="docup-skip" href="#docup-content">Skip to content</a>

    @if($banner !== null)
        {{--
            §8.14.1's version-scoped banner. `role="status"` rather than
            `role="alert"`: it is present from first paint, so an assertive
            region would announce nothing, and "you are reading an old version"
            is information rather than an emergency.
        --}}
        <div class="docup-banner docup-banner--{{ $banner['tone'] }}" role="status">
            {{ $banner['text'] }}
        </div>
    @endif

    @if($announcement !== null)
        {{--
            §8.14.3's announcement. The markup is DocUp's own output from
            {@see App\Branding\Chrome\InlineMarkup} — five elements, one
            attribute — so `{!! !!}` here is printing bytes this application
            wrote, never a tenant's input.
        --}}
        <div class="docup-announcement docup-announcement--{{ $announcement['tone'] }}" role="status">
            {!! $announcement['markup'] !!}
        </div>
    @endif

    <header class="docup-header">
        <a class="docup-brand" href="/">
            @if($logo !== null)
                {{--
                    🛑 §8.14.11: "rendered **only via `<img src>`** from a
                    dedicated asset host". The `alt` is the wordmark, because
                    the logo is a link to the home page and a link needs an
                    accessible name — and the uploaded filename was discarded
                    at ingest, so there is nothing else it could be.

                    `width`/`height` are the stored dimensions, so the header
                    does not resize when the image arrives (WCAG 2.2 has no
                    layout-shift criterion; a reader with a tremor still
                    deserves a target that stays put).
                --}}
                <img src="{{ $logo['url'] }}" alt="{{ $logo['alt'] }}"
                     @if($logo['width'] !== null) width="{{ $logo['width'] }}" @endif
                     @if($logo['height'] !== null) height="{{ $logo['height'] }}" @endif>
            @else
                <span class="docup-wordmark">{{ $brand }}</span>
            @endif
        </a>

        @if($navigation !== [])
            <nav class="docup-nav" aria-label="Documentation sections">
                <ul>
                    @foreach($navigation as $index => $link)
                        {{--
                            `aria-current="page"` on the first entry only, as
                            an example: a consumer sets it on whichever link
                            matches the page. WCAG 2.2 SC 2.4.8.
                        --}}
                        <li><a href="{{ $link['href'] }}" @if($index === 0) aria-current="page" @endif>{{ $link['label'] }}</a></li>
                    @endforeach
                </ul>
            </nav>
        @endif

        @if($schemeToggle)
            {{--
                🛑 A real `<button>` with a real accessible name. The
                `aria-pressed` state is what a screen reader announces; an icon
                with no name is the single most common chrome accessibility
                failure.
            --}}
            <button type="button" class="docup-scheme" aria-pressed="false">
                Dark colour scheme
            </button>
        @endif
    </header>

    <main id="docup-content" class="docup-main">
        <h1>{{ $brand }} documentation</h1>

        @foreach($homepage as $block)
            @if($block['type'] === 'hero')
                <section class="docup-hero" aria-labelledby="docup-hero-heading">
                    <h2 id="docup-hero-heading">{{ $block['heading'] }}</h2>
                    @isset($block['body'])<p>{{ $block['body'] }}</p>@endisset
                    @isset($block['primary_href'])
                        <a class="docup-action" href="{{ $block['primary_href'] }}">{{ $block['primary_label'] ?? 'Read the guide' }}</a>
                    @endisset
                </section>
            @elseif($block['type'] === 'cards')
                <section class="docup-cards" aria-labelledby="docup-cards-heading">
                    <h2 id="docup-cards-heading">{{ $block['heading'] ?? 'Start here' }}</h2>
                    <ul>
                        @foreach($block['cards'] ?? [] as $card)
                            <li><a href="{{ $card['href'] }}">{{ $card['label'] }}</a></li>
                        @endforeach
                    </ul>
                </section>
            @elseif($block['type'] === 'prose')
                <section class="docup-prose" aria-labelledby="docup-prose-heading">
                    <h2 id="docup-prose-heading">{{ $block['heading'] ?? 'About' }}</h2>
                    <p>{{ $block['body'] }}</p>
                </section>
            @elseif($block['type'] === 'callout')
                <p class="docup-callout"><a href="{{ $block['href'] }}">{{ $block['label'] }}</a></p>
            @elseif($block['type'] === 'search')
                {{--
                    🛑 A `<label>` bound to the field, not a placeholder. A
                    placeholder is not an accessible name and disappears on
                    input (WCAG 2.2 SC 3.3.2). §8.15.8 specifies the full
                    combobox pattern for the live control; this is the static
                    affordance it progressively enhances.
                --}}
                <form class="docup-search" role="search" action="/_/search" method="get">
                    <label for="docup-search-input">Search the documentation</label>
                    <input id="docup-search-input" type="search" name="q"
                           @isset($block['placeholder']) placeholder="{{ $block['placeholder'] }}" @endisset>
                    <button type="submit">Search</button>
                </form>
            @elseif($block['type'] === 'versions')
                <section class="docup-versions" aria-labelledby="docup-versions-heading">
                    <h2 id="docup-versions-heading">{{ $block['heading'] ?? 'Versions' }}</h2>
                    <p>A consumer renders the version list from <code>/_/addons</code>.</p>
                </section>
            @endif
        @endforeach

        @if($homepage === [])
            <p>This theme declares no homepage blocks, so a consumer renders the documentation directly.</p>
        @endif
    </main>

    <footer class="docup-footer">
        @foreach($footer as $groupIndex => $group)
            <nav aria-labelledby="docup-footer-{{ $groupIndex }}">
                {{--
                    🛑 A heading the `aria-labelledby` points at, so each footer
                    group is a distinguishable landmark. Several `<nav>`
                    elements with no names is the other common chrome failure:
                    a screen reader announces "navigation" four times.
                --}}
                <h2 id="docup-footer-{{ $groupIndex }}">{{ $group['label'] }}</h2>
                <ul>
                    @foreach($group['links'] as $link)
                        <li><a href="{{ $link['href'] }}">{{ $link['label'] }}</a></li>
                    @endforeach
                </ul>
            </nav>
        @endforeach

        <p class="docup-colophon">{{ $brand }}</p>
    </footer>
</body>
</html>
